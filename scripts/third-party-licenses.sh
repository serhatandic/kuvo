#!/bin/sh
# Writes THIRD_PARTY_LICENSES.txt from Licenses/ and the release pins.
set -eu
cd "$(dirname "$0")/.."

section() { # name, version, location, note, license file
    printf '\n\n%s %s\n%s\n' "$1" "$2" "$3"
    [ -n "$4" ] && printf '%s\n' "$4"
    printf '\n'
    cat "$5"
}

{
    cat <<'HEADER'
THIRD-PARTY LICENSES
====================

This file lists the license terms for third-party code in Kuvo Code. It is
generated by scripts/third-party-licenses.sh. It does not change Kuvo Code's
own license.

The box installs the pinned @opencode/cli binary separately. Its license is
included below.
HEADER

    section OpenUsage "(provider icons)" https://github.com/robinebers/openusage \
        "Provider icons in gpui/assets/marks, unchanged." \
        Licenses/openusage.txt
    section browser-use 0.4.2 https://github.com/browser-use/browser-use \
        "box/src/browser/buildDomTree.js, unchanged." \
        Licenses/browser-use.txt
    section "Work Queue Markdown parser" 2.0.3 https://github.com/syntax-tree/mdast-util-from-markdown \
        "Bundled in kuvo-link.js. Includes micromark and the runtime dependencies listed below." \
        Licenses/work-queue-markdown.txt
    section models.dev "(logos, 2026-11-01)" https://models.dev \
        "Providers' logos in gpui/assets/marks/providers, unchanged. Each logo is its owner's trademark, shown only to name its provider." \
        Licenses/models.dev.txt
    section GPUI "(Zed, rev dc93abce)" https://github.com/zed-industries/zed/tree/main/crates/gpui \
        "The UI framework of the GPUI client in gpui/. Parts of gpui/kuvo_ui/src/text_field are adapted from its examples/input.rs. Every Rust crate the client builds on, and its license, is listed in gpui/LICENSES-DEPS.md." \
        Licenses/gpui.txt
    section option-ext 0.2.0 https://github.com/soc/option-ext \
        "Linked unmodified into the GPUI client through GPUI's font loading (font-kit, dirs). Its source is at the location above and on crates.io (crates.io/crates/option-ext)." \
        Licenses/option-ext.txt
    section x25519-dalek 2.0.1 https://github.com/dalek-cryptography/curve25519-dalek/tree/main/x25519-dalek \
        "BSD-3-Clause. In the GPUI client: the keys and handshake of its link to your other computers." \
        Licenses/x25519-dalek.txt
    section curve25519-dalek 4.1.3 https://github.com/dalek-cryptography/curve25519-dalek \
        "BSD-3-Clause. In the GPUI client, through x25519-dalek." \
        Licenses/curve25519-dalek.txt
    section ring 0.17.14 https://github.com/briansmith/ring \
        "Apache-2.0 AND ISC. In the GPUI client: the cryptography of its TLS connection to the relay." \
        Licenses/ring.txt
    section rustls-webpki 0.103.17 https://github.com/rustls/webpki \
        "ISC. In the GPUI client: checking the relay's certificate." \
        Licenses/rustls-webpki.txt
    section webpki-roots 1.0.12 https://github.com/rustls/webpki-roots \
        "CDLA-Permissive-2.0. In the GPUI client: Mozilla's list of certificate authorities, as data, unmodified." \
        Licenses/webpki-roots.txt

    section Sparkle "$(sed -n 's/^VERSION=//p' scripts/sparkle.sh)" https://github.com/sparkle-project/Sparkle \
        "The updater carried in the desktop app bundle." \
        Licenses/Sparkle.txt

    section opencode "$(python3 -c 'import json; print(json.load(open("box/src/shared/engine-pin.json"))["version"])')" \
        https://github.com/anomalyco/opencode \
        "Installed separately by the box." \
        Licenses/opencode.txt
} > THIRD_PARTY_LICENSES.txt

echo "Wrote THIRD_PARTY_LICENSES.txt"
