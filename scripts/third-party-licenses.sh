#!/bin/sh
# Writes THIRD_PARTY_LICENSES.txt from the packages pinned in Package.resolved.
# CI runs this and fails if the committed file is out of date.
set -eu
cd "$(dirname "$0")/.."

swift package resolve >/dev/null

{
    cat <<'HEADER'
THIRD-PARTY LICENSES
====================

This file lists the license terms for third-party code built into Kuvo. It is
generated by scripts/third-party-licenses.sh from Package.resolved. It does not
change Kuvo's own license.

Kuvo does not include Linux or Docker. On first launch it downloads Alpine
Linux from dl-cdn.alpinelinux.org and installs Docker Engine and its
dependencies from Alpine's package repository, under their own licenses.
HEADER
    python3 - <<'PY'
import json
for pin in sorted(json.load(open("Package.resolved"))["pins"], key=lambda p: p["identity"]):
    print(f'{pin["location"]}|{pin["state"].get("version") or pin["state"]["revision"]}')
PY
} | {
    # Header lines pass through; each "location|version" line becomes a section.
    while IFS= read -r line; do
        case "$line" in
            https://*\|*)
                location=${line%%|*}
                version=${line#*|}
                name=$(basename "$location" .git)
                license=$(find ".build/checkouts/$name" -maxdepth 1 \( -iname 'LICENSE*' -o -iname 'COPYING*' \) | sort | head -n 1)
                if [ -z "$license" ]; then
                    echo "No license file found for $name" >&2
                    exit 1
                fi
                printf '\n\n%s %s\n%s\n\n' "$name" "$version" "$location"
                cat "$license"
                ;;
            *) printf '%s\n' "$line" ;;
        esac
    done
} > THIRD_PARTY_LICENSES.txt

echo "Wrote THIRD_PARTY_LICENSES.txt"
