#!/bin/sh
# Writes THIRD_PARTY_LICENSES.txt: the code copied into this repository, the Swift
# packages pinned in the Xcode project's Package.resolved, and the engine the app
# downloads. CI runs this and fails if the committed file is out of date.
set -eu
cd "$(dirname "$0")/.."

resolved=swift/KuvoCode.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved
checkouts=build/SourcePackages/checkouts
# Pinned only because a dependency's own tools need it; nothing from it is in the app.
build_only="swift-argument-parser"

xcodebuild -resolvePackageDependencies -project swift/KuvoCode.xcodeproj -scheme KuvoCode \
    -clonedSourcePackagesDirPath build/SourcePackages >/dev/null

section() { # name, version, location, note, license file
    printf '\n\n%s %s\n%s\n' "$1" "$2" "$3"
    [ -n "$4" ] && printf '%s\n' "$4"
    printf '\n'
    cat "$5"
}

{
    cat <<'HEADER'
THIRD-PARTY LICENSES
====================

This file lists the license terms for third-party code in Kuvo Code. It is
generated by scripts/third-party-licenses.sh. It does not change Kuvo Code's
own license.

Kuvo Code does not include the opencode engine. On first launch it downloads
the official @opencode/cli binary from the npm registry; its license is near
the end. Nor does it include Whisper's model: voice input downloads it the first
time it's used; its license is the last one below.
HEADER

    section OpenUsage fork https://github.com/robinebers/openusage \
        "swift/UsageKit is a fork of OpenUsage, not the official OpenUsage. The OpenUsage name and logo are trademarks of Robin Ebers and aren't used. Its provider icons are also among ClientDesign's marks (swift/KuvoClient/Sources/ClientDesign/Resources/Marks.xcassets)." \
        swift/UsageKit/LICENSE
    section Textual 0.5.0 https://github.com/gonzalezreal/textual \
        "swift/Textual is a copy of Textual with Kuvo Code's changes (see its README)." \
        swift/Textual/LICENSE
    section Prism 1.29.0 https://prismjs.com \
        "swift/KuvoCode/Resources/prism-bundle.js, with its language definitions, as bundled by Textual's Scripts/bundle-prism.sh." \
        Licenses/Prism.txt
    section Mermaid 12.3.0 https://github.com/mermaid-js/mermaid \
        "swift/KuvoCode/Resources/mermaid.min.js, unchanged, as published on npm; the libraries it bundles are under their own licenses, MIT or similar." \
        Licenses/mermaid.txt
    section browser-use 0.4.2 https://github.com/browser-use/browser-use \
        "box/src/browser/buildDomTree.js, unchanged." \
        Licenses/browser-use.txt
    section "Work Queue Markdown parser" 2.0.3 https://github.com/syntax-tree/mdast-util-from-markdown \
        "Bundled in kuvo-link.js. Includes micromark and the runtime dependencies listed below." \
        Licenses/work-queue-markdown.txt
    section models.dev "(logos, 2026-11-01)" https://models.dev \
        "Providers' logos in swift/KuvoClient/Sources/ClientDesign/Resources/Marks.xcassets, unchanged. Each logo is its owner's trademark, shown only to name its provider." \
        Licenses/models.dev.txt
    section "Simple Icons" 16.35.0 https://simpleicons.org \
        "Services' marks in swift/KuvoClient/Sources/ClientDesign/Resources/Marks.xcassets, unchanged. Each mark is its owner's trademark, shown only to name its service." \
        Licenses/simple-icons.txt
    section GPUI "(Zed, rev dc93abce)" https://github.com/zed-industries/zed/tree/main/crates/gpui \
        "The UI framework of the GPUI client in gpui/. Parts of gpui/kuvo_ui/src/text_field are adapted from its examples/input.rs. Every Rust crate the client builds on, and its license, is listed in gpui/LICENSES-DEPS.md." \
        Licenses/gpui.txt
    section option-ext 0.2.0 https://github.com/soc/option-ext \
        "Linked unmodified into the GPUI client through GPUI's font loading (font-kit, dirs). Its source is at the location above and on crates.io (crates.io/crates/option-ext)." \
        Licenses/option-ext.txt
    section x25519-dalek 2.0.1 https://github.com/dalek-cryptography/curve25519-dalek/tree/main/x25519-dalek \
        "BSD-3-Clause. In the GPUI client: the keys and handshake of its link to your other computers." \
        Licenses/x25519-dalek.txt
    section curve25519-dalek 4.1.3 https://github.com/dalek-cryptography/curve25519-dalek \
        "BSD-3-Clause. In the GPUI client, through x25519-dalek." \
        Licenses/curve25519-dalek.txt
    section ring 0.17.14 https://github.com/briansmith/ring \
        "Apache-2.0 AND ISC. In the GPUI client: the cryptography of its TLS connection to the relay." \
        Licenses/ring.txt
    section rustls-webpki 0.103.17 https://github.com/rustls/webpki \
        "ISC. In the GPUI client: checking the relay's certificate." \
        Licenses/rustls-webpki.txt
    section webpki-roots 1.0.12 https://github.com/rustls/webpki-roots \
        "CDLA-Permissive-2.0. In the GPUI client: Mozilla's list of certificate authorities, as data, unmodified." \
        Licenses/webpki-roots.txt

    python3 - "$resolved" <<'PY' | while IFS='|' read -r location version; do
import json, sys
for pin in sorted(json.load(open(sys.argv[1]))["pins"], key=lambda p: p["identity"]):
    print(f'{pin["location"]}|{pin["state"].get("version") or pin["state"]["revision"]}')
PY
        name=$(basename "$location" .git)
        case " $build_only " in *" $name "*) continue ;; esac
        license=$(find "$checkouts/$name" -maxdepth 1 \( -iname 'LICENSE*' -o -iname 'COPYING*' \) | sort | head -n 1)
        if [ -z "$license" ]; then
            echo "No license file found for $name" >&2
            exit 1
        fi
        note=""
        if [ "$name" = swiftui-math ]; then
            note="Its math fonts are under the SIL Open Font License 1.1 and the GUST Font License, whose texts ship next to the fonts in the app."
        fi
        section "$name" "$version" "$location" "$note" "$license"
    done

    section opencode "$(sed -n 's/.*cli-darwin-arm64-\([0-9.]*\)\.tgz.*/\1/p' swift/OpenCodeKit/Sources/OpenCodeKit/Engine/EngineInstaller.swift)" \
        https://github.com/anomalyco/opencode \
        "Downloaded on first launch, not included in the app." \
        Licenses/opencode.txt
    section "Whisper large-v3-turbo" "(Core ML)" https://github.com/openai/whisper \
        "Downloaded the first time voice input is used, not included in the app: Argmax's Core ML build (huggingface.co/argmaxinc/whisperkit-coreml, MIT) of OpenAI's model, and its tokenizer (huggingface.co/openai/whisper-large-v3)." \
        Licenses/whisper.txt
} > THIRD_PARTY_LICENSES.txt

echo "Wrote THIRD_PARTY_LICENSES.txt"
